import { matchKey } from './normalize.mjs'

// Dedupes catalog rows on (platform, matchKey(title)) — the same
// normalisation the app uses to compare titles, so a "Paw Patrol:
// Chase" from one source and "Paw Patrol — Chase" from another
// collapse into one row. Prefers a row that has an image.
export function dedupeCatalog(rows) {
  const byKey = new Map()
  for (const row of rows) {
    const key = `${row.platform}|${matchKey(row.title)}`
    const existing = byKey.get(key)
    if (!existing || (!existing.image_url && row.image_url)) byKey.set(key, row)
  }
  return [...byKey.values()].sort(
    (a, b) => a.platform.localeCompare(b.platform) || a.title.localeCompare(b.title)
  )
}

const sqlStr = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`

// Idempotent SQL for the catalog: paste into the Supabase SQL editor,
// or save as a migration. Upserts on the (platform, title) unique key
// so re-running the ingestor refreshes details/images in place.
export function catalogToSql(rows) {
  const values = rows
    .map(
      (r, i) =>
        `  (${sqlStr(r.platform)}, ${sqlStr(r.title)}, ${sqlStr(r.details)}, ${sqlStr(r.image_url)}, ${i + 1})`
    )
    .join(',\n')
  return `-- Generated by the Toy Library ingestor — do not hand-edit.
-- ${rows.length} catalog rows.
insert into public.catalog_items (platform, title, details, image_url, sort_order) values
${values}
on conflict (platform, title) do update
  set details = excluded.details,
      image_url = excluded.image_url,
      sort_order = excluded.sort_order;
`
}

// Applies rows directly with the service-role key (bypasses RLS —
// catalog_items intentionally has no write policies for app users).
export async function applyToSupabase(rows, { url, serviceKey }) {
  const { createClient } = await import('@supabase/supabase-js')
  const supabase = createClient(url, serviceKey, { auth: { persistSession: false } })
  const payload = rows.map((r, i) => ({
    platform: r.platform,
    title: r.title,
    details: r.details,
    image_url: r.image_url,
    sort_order: i + 1,
  }))
  const CHUNK = 500
  for (let i = 0; i < payload.length; i += CHUNK) {
    const { error } = await supabase
      .from('catalog_items')
      .upsert(payload.slice(i, i + CHUNK), { onConflict: 'platform,title' })
    if (error) throw new Error(`Supabase upsert failed: ${error.message}`)
  }
  return payload.length
}
